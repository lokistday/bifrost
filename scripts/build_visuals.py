"""Validate authored diagrams and bundle them for static, offline-friendly pages."""
from pathlib import Path
import json
from build_courses import load_courses

ROOT = Path(__file__).resolve().parents[1]


def build():
    source = ROOT / 'content' / 'visuals.json'
    data = json.loads(source.read_text(encoding='utf-8'))
    _, authored = load_courses(strict=False)
    lessons = {l['id'] for c in authored.values() for m in c['modules'] for l in m['lessons']}
    courses = set(authored)
    assert data['version'] == 1, 'Unknown diagram format'
    assert set(data['lessons']) == lessons, 'Lesson diagram coverage differs from curriculum'
    assert set(data['courses']) == courses, 'Course diagram coverage differs from curriculum'
    required = {'flow': 'steps', 'sequence': 'messages', 'compare': 'panels',
                'table': 'rows', 'timeline': 'events', 'map': 'nodes', 'cells': 'rows', 'pixels': 'pixels', 'wheel': None}
    for key, diagram in [*data['lessons'].items(), *data['courses'].items()]:
        assert diagram['type'] in required, f'Unknown diagram type: {key}'
        for field in ['title', 'description', 'takeaway']:
            assert isinstance(diagram[field], str) and diagram[field].strip(), f'Missing {field}: {key}'
        content = required[diagram['type']]
        if content:
            assert diagram[content], f'Empty diagram: {key}'
        if diagram['type'] == 'map':
            nodes = {node[0] for node in diagram['nodes']}
            assert len(nodes) == len(diagram['nodes']), f'Duplicate node ID: {key}'
            for edge in diagram.get('edges', []):
                if 'points' not in edge:
                    assert edge['from'] in nodes and edge['to'] in nodes, f'Unknown endpoint: {key}'
        if diagram['type'] == 'table':
            assert all(len(row) == len(diagram['columns']) for row in diagram['rows']), f'Uneven table: {key}'
        if diagram['type'] == 'compare':
            assert len({len(panel['rows']) for panel in diagram['panels']}) == 1, f'Uneven comparison: {key}'
        if diagram['type'] == 'pixels':
            width, height, maximum = (diagram.get(name) for name in ['width', 'height', 'maximum'])
            assert all(type(n) is int and 1 <= n <= 4 for n in [width, height]), f'Pixel grid dimensions: {key}'
            assert type(maximum) is int and 1 <= maximum <= 255, f'Pixel sample maximum: {key}'
            assert len(diagram['pixels']) == width * height, f'Pixel sample count: {key}'
            assert all(isinstance(rgb, list) and len(rgb) == 3 and all(type(n) is int and 0 <= n <= maximum for n in rgb)
                       for rgb in diagram['pixels']), f'Pixel RGB values: {key}'
    bundle = '/* Generated by scripts/build_visuals.py from content/visuals.json. */\n'
    bundle += 'window.BifrostVisualData = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'
    (ROOT / 'js' / 'visual-data.js').write_text(bundle, encoding='utf-8', newline='\n')
    return len(lessons), len(courses)


if __name__ == '__main__':
    lessons, courses = build()
    print(f'Bundled {lessons} lesson diagrams and {courses} course diagrams.')
